"""Generate the browser's output event type from the Pydantic source of truth."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from backend.models import Event


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(value) for value in schema["anyOf"])
    return {"string": "string", "integer": "number", "number": "number",
            "boolean": "boolean", "null": "null"}[schema["type"]]


def render():
    schema = Event.model_json_schema()
    output = "// Generated by scripts/export_event_type.py; do not edit.\n"
    for name, value in {**schema.get("$defs", {}), "Event": schema}.items():
        output += f"export type {name} = {{\n"
        for field, definition in value["properties"].items():
            output += f"  {field}: {ts_type(definition)};\n"
        output += "};\n"
    return output


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / "frontend/lib/events.ts"
    target.parent.mkdir(exist_ok=True)
    target.write_text(render(), encoding="utf-8")
